"use client";

import { useEffect, useState } from "react";

export default function BlogTldr({
  blogId,
  contentId,
}: {
  blogId: string;
  contentId: string;
}) {
  const [bullets, setBullets] = useState<string[] | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [speaking, setSpeaking] = useState(false);
  const cacheKey = `tldr:${blogId}`;

  useEffect(() => {
    try {
      const cached = sessionStorage.getItem(cacheKey);
      if (cached) setBullets(JSON.parse(cached));
    } catch {
      // storage unavailable
    }
    return () => window.speechSynthesis?.cancel();
  }, [cacheKey]);

  const generate = async () => {
    const text = document.getElementById(contentId)?.innerText ?? "";
    if (text.trim().length < 200) {
      setError("This article is too short to summarise.");
      return;
    }
    setLoading(true);
    setError("");
    try {
      const res = await fetch("/api/ai/tldr", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ id: blogId, text: text.slice(0, 12000) }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "Failed");
      setBullets(data.bullets);
      try {
        sessionStorage.setItem(cacheKey, JSON.stringify(data.bullets));
      } catch {
        // ignore
      }
    } catch (e) {
      setError((e as Error).message || "Couldn't summarise right now.");
    } finally {
      setLoading(false);
    }
  };

  const toggleSpeech = () => {
    const synth = window.speechSynthesis;
    if (!synth || !bullets) return;
    if (speaking) {
      synth.cancel();
      setSpeaking(false);
      return;
    }
    const utterance = new SpeechSynthesisUtterance(
      `Summary. ${bullets.join(". ")}`
    );
    utterance.onend = () => setSpeaking(false);
    utterance.onerror = () => setSpeaking(false);
    synth.cancel();
    synth.speak(utterance);
    setSpeaking(true);
  };

  return (
    <div className="my-6 rounded-xl border border-cyan-500/30 bg-cyan-500/5 p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <span className="font-semibold text-primary_dark dark:text-cyan-300">
          ✨ AI TL;DR
        </span>
        <div className="flex gap-2">
          {bullets && (
            <button
              type="button"
              onClick={toggleSpeech}
              className="rounded-lg border border-primary px-3 py-1 text-sm text-primary_dark dark:text-cyan-200"
            >
              {speaking ? "Stop" : "🔊 Listen"}
            </button>
          )}
          {!bullets && (
            <button
              type="button"
              onClick={generate}
              disabled={loading}
              className="rounded-lg bg-primary_dark px-3 py-1 text-sm text-white disabled:opacity-60"
            >
              {loading ? "Summarising…" : "Summarise this article"}
            </button>
          )}
        </div>
      </div>
      {bullets && (
        <ul className="mt-3 list-disc space-y-1 pl-5 text-sm text-gray-800 dark:text-gray-200">
          {bullets.map((b, i) => (
            <li key={i}>{b}</li>
          ))}
        </ul>
      )}
      {error && <p className="mt-2 text-sm text-red-500">{error}</p>}
      <p className="mt-2 text-[11px] text-gray-500">
        Generated by AI from the article text, so it may miss nuance.
      </p>
    </div>
  );
}
